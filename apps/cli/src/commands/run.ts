import { spawn } from 'node:child_process';
import { basename } from 'node:path';
import process from 'node:process';
import spawnCommand from 'cross-spawn';
import { findOnPath } from '../integrations/executables';
import { sendNotice } from '../operations';
import { withProgress } from '../progress';
import { muted, ui } from '../ui';
import { UsageError } from './usage';

/**
 * What the alert calls a command: the program and, when it is a plain word,
 * its subcommand ("pnpm test", "make deploy"). Arguments never leave the
 * computer: they can hold tokens, paths or private names.
 */
export function commandLabel(argv: string[]): string {
  const [program, next] = argv;
  const name = basename(program ?? 'command');
  return next && /^[A-Za-z][\w:.-]{0,30}$/.test(next) ? `${name} ${next}` : name;
}

/** "45s", "4m 12s", "1h 3m". */
export function durationText(ms: number): string {
  const seconds = Math.max(0, Math.round(ms / 1000));
  if (seconds < 60) return `${seconds}s`;
  const minutes = Math.floor(seconds / 60);
  if (minutes < 60) return `${minutes}m ${seconds % 60}s`;
  return `${Math.floor(minutes / 60)}h ${minutes % 60}m`;
}

/**
 * Runs a command with this terminal and sends one alert when it ends: whether
 * it succeeded, its exit code and how long it took. Exits with the command's
 * code, so it fits in scripts. An interrupted command (Ctrl+C) alerts
 * nobody: the user is at the keyboard.
 */
export async function run(
  argv: string[],
  options: { onFail?: boolean; title?: string },
): Promise<number> {
  if (argv.length === 0)
    throw new UsageError('run', 'Give the command to run: greatping run -- pnpm test');
  // A line break can introduce a second command in a Windows batch launcher.
  // Never silently reinterpret a caller's argument as shell syntax.
  let needsWindowsAdapter = false;
  if (process.platform === 'win32') {
    const program = argv[0] as string;
    const native =
      /\.(?:exe|com)$/i.test(program) || /\.(?:exe|com)$/i.test(findOnPath(program) ?? '');
    needsWindowsAdapter = !native;
    if (argv.some((value) => value.includes('\0') || (!native && /[\r\n]/.test(value))))
      throw new UsageError('run', 'Windows batch commands cannot contain NUL or line breaks.');
  }
  const label = options.title?.trim() || commandLabel(argv);
  const started = Date.now();
  const outcome = await new Promise<{ code: number; signal?: NodeJS.Signals; error?: Error }>(
    (resolve) => {
      // Pipe-driven commands can own a process group, allowing cancellation to
      // stop descendants without signalling the caller's shell. Interactive
      // commands stay in the terminal group so stdin/job control still works.
      const ownGroup = process.platform !== 'win32' && !process.stdin.isTTY;
      // Native commands must never be reinterpreted as shebang scripts by an
      // adapter (even a script misleadingly named .exe). Node starts them
      // directly; only Windows batch/script launchers need cross-spawn.
      const child = (needsWindowsAdapter ? spawnCommand : spawn)(argv[0] as string, argv.slice(1), {
        stdio: 'inherit',
        detached: ownGroup,
      });
      let interrupted: NodeJS.Signals | undefined;
      let escalation: ReturnType<typeof setTimeout> | undefined;
      let finished = false;
      const send = (signal: NodeJS.Signals) => {
        if (!child.pid) return;
        try {
          if (ownGroup) process.kill(-child.pid, signal);
          else if (process.platform === 'win32') {
            // Node cannot deliver POSIX signals on Windows. taskkill scopes the
            // forced tree termination to the child created by this wrapper.
            const killer = spawn('taskkill', ['/PID', String(child.pid), '/T', '/F'], {
              stdio: 'ignore',
            });
            killer.on('error', () => child.kill(signal));
          } else child.kill(signal);
        } catch (error) {
          if ((error as NodeJS.ErrnoException).code !== 'ESRCH') child.kill(signal);
        }
      };
      const cancel = (signal: NodeJS.Signals) => {
        if (finished) return;
        if (interrupted) {
          send('SIGKILL');
          return;
        }
        interrupted = signal;
        // The terminal already delivers SIGINT to an attached child. Node does
        // not expose its source, so relaying could turn one Ctrl+C into two.
        // A PID-only TTY SIGINT uses the bounded forced-shutdown fallback below.
        // SIGTERM is not generated by terminal Ctrl+C and is forwarded at once.
        if (!process.stdin.isTTY || signal !== 'SIGINT') send(signal);
        // Same graceful shutdown budget as the installed execa runner.
        escalation = setTimeout(() => send('SIGKILL'), 5000);
      };
      const interrupt = () => cancel('SIGINT');
      const terminate = () => cancel('SIGTERM');
      process.on('SIGINT', interrupt);
      process.on('SIGTERM', terminate);
      const done = (result: { code: number; signal?: NodeJS.Signals; error?: Error }) => {
        if (finished) return;
        finished = true;
        clearTimeout(escalation);
        process.off('SIGINT', interrupt);
        process.off('SIGTERM', terminate);
        // The group leader may exit before its descendants finish. After an
        // interrupted command, none of that private process group should linger.
        if (interrupted && ownGroup) send('SIGKILL');
        resolve(
          interrupted
            ? { code: 128 + (signalNumber(interrupted) ?? 0), signal: interrupted }
            : result,
        );
      };
      child.on('error', (error) => done({ code: 127, error }));
      child.on('exit', (code, signal) =>
        done(signal ? { code: 128 + (signalNumber(signal) ?? 0), signal } : { code: code ?? 1 }),
      );
    },
  );
  const elapsed = durationText(Date.now() - started);
  if (outcome.error) ui.error(`Could not start ${label}.`, outcome.error.message);
  if (outcome.signal === 'SIGINT' || outcome.signal === 'SIGTERM') return outcome.code;
  const failed = outcome.code !== 0;
  if (!failed && options.onFail) return outcome.code;
  const message = outcome.error
    ? `Could not start: ${outcome.error.message}`
    : failed
      ? `Exit code ${outcome.code}${outcome.signal ? ` (${outcome.signal})` : ''} after ${elapsed}.`
      : `Finished in ${elapsed}.`;
  try {
    const sent = await withProgress(
      'Sending completion notice to GreatPing',
      (signal) => sendNotice(message, `${label} ${failed ? 'failed' : 'succeeded'}`, signal),
      {
        interrupted:
          'Completion notice interrupted. GreatPing may have accepted it; check the app.',
      },
    );
    if (sent.status === 'paused')
      ui.warn(`${label} ended; alerts from this computer are paused, so nobody was alerted.`);
  } catch (error) {
    // The command's result matters more than the alert: report and keep its code.
    ui.warn(
      `${label} ended, but GreatPing could not send the alert: ${error instanceof Error ? error.message : String(error)}`,
    );
    ui.next(muted('Check the pairing with greatping status.'));
  }
  return outcome.code;
}

function signalNumber(signal: NodeJS.Signals): number | undefined {
  return ({ SIGHUP: 1, SIGINT: 2, SIGQUIT: 3, SIGKILL: 9, SIGTERM: 15 } as Record<string, number>)[
    signal
  ];
}
